import type { VerifyReport } from '@concilium/core';

export type VerifyOutputFormat = 'json' | 'text' | 'markdown';

export function formatVerifyReport(report: VerifyReport, format: VerifyOutputFormat): string {
  switch (format) {
    case 'json':
      return JSON.stringify(report, null, 2);
    case 'markdown':
      return formatMarkdown(report);
    case 'text':
      return formatText(report);
  }
}

function verdictBadge(verdict: 'PASS' | 'FAIL'): string {
  return verdict === 'PASS' ? '✅ PASS' : '❌ FAIL';
}

function formatText(report: VerifyReport): string {
  const lines: string[] = [];
  lines.push(`Verdict: ${report.verdict} (confidence: ${report.confidence}%, threshold: ${report.threshold}%)`);
  lines.push(`PR: ${report.repo}#${report.prNumber}`);
  lines.push(`Cost: $${report.totalCostUsd.toFixed(4)}`);
  lines.push(`Duration: ${(report.durationMs / 1000).toFixed(1)}s`);

  if (report.disagreements.length > 0) {
    lines.push('');
    lines.push('Disagreements:');
    for (const d of report.disagreements) {
      lines.push(`  - ${d.agentName}: juror ${d.jurorModel} ranked #${d.rank} (median: ${d.medianRank}, delta: ${d.delta.toFixed(1)})`);
    }
  }

  if (report.consensusRanking.length > 0) {
    lines.push('');
    lines.push('Consensus ranking:');
    report.consensusRanking.forEach((agent, i) => {
      lines.push(`  ${i + 1}. ${agent}`);
    });
  }

  return lines.join('\n');
}

function formatMarkdown(report: VerifyReport): string {
  const lines: string[] = [];

  lines.push(`## ${verdictBadge(report.verdict)}`);
  lines.push('');
  lines.push(`**Confidence**: ${report.confidence}% (threshold: ${report.threshold}%)`);
  lines.push(`**PR**: ${report.repo}#${report.prNumber}`);
  lines.push(`**Cost**: $${report.totalCostUsd.toFixed(4)} | **Duration**: ${(report.durationMs / 1000).toFixed(1)}s`);

  if (report.disagreements.length > 0) {
    lines.push('');
    lines.push('### Disagreements');
    lines.push('');
    lines.push('| Agent | Juror | Rank | Median Rank | Delta |');
    lines.push('|-------|-------|------|-------------|-------|');
    for (const d of report.disagreements) {
      lines.push(`| ${d.agentName} | ${d.jurorModel} | ${d.rank} | ${d.medianRank} | ${d.delta.toFixed(1)} |`);
    }
  }

  if (report.consensusRanking.length > 0) {
    lines.push('');
    lines.push('### Consensus Ranking');
    lines.push('');
    report.consensusRanking.forEach((agent, i) => {
      lines.push(`${i + 1}. ${agent}`);
    });
  }

  if (report.synthesis) {
    lines.push('');
    lines.push('<details><summary>Full Synthesis</summary>');
    lines.push('');
    lines.push(report.synthesis);
    lines.push('');
    lines.push('</details>');
  }

  lines.push('');
  lines.push('---');
  lines.push(`*Generated by [Concilium](https://concilium.dev) at ${report.createdAt}*`);

  return lines.join('\n');
}
